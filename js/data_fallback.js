  getDigest: function(hoursWindow, categoryFilter) {
    hoursWindow = hoursWindow || 24;
    var now = new Date();
    var cutoff = new Date(now.getTime() - (hoursWindow * 60 * 60 * 1000));
    var raw = this.data.announcements.filter(function(item) {
      var itemTime = new Date(item.timestamp);
      if (itemTime < cutoff) return false;
      if (categoryFilter && categoryFilter !== 'all' && item.category !== categoryFilter) return false;
      return true;
    });

    var priority = [];
    var routine = [];
    var counts = {};

    raw.forEach(function(item) {
      counts[item.category] = (counts[item.category] || 0) + 1;
      if (item.priority === 'HIGH' || item.priority === 'MEDIUM') {
        priority.push(item);
      } else {
        routine.push(item);
      }
    });

    return {
      metadata: {
        window_hours: hoursWindow,
        window_label: hoursWindow <= 24 ? ('Last ' + hoursWindow + ' Hours') : ('Last ' + Math.round(hoursWindow / 24) + ' Days'),
        total_filings_count: raw.length,
        priority_count: priority.length,
        routine_collapsed_count: routine.length,
        category_distribution: counts
      },
      priority_items: priority,
      routine_items: routine
    };
  },

  getAlerts: function(priceThresh, volThresh) {
    priceThresh = parseFloat(priceThresh) || 3.0;
    volThresh = parseFloat(volThresh) || 2.0;

    var priceAnomalies = [];
    var volumeSpikes = [];
    var materialFilings = [];

    this.data.all_companies.forEach(function(c) {
      var chg = c.change_pct || 0;
      if (Math.abs(chg) >= priceThresh) {
        priceAnomalies.push({
          ticker: c.ticker,
          symbol: c.symbol,
          name: c.name,
          change_pct: chg,
          last_price: c.last_price,
          direction: chg > 0 ? 'SURGE' : 'PLUNGE',
          message: 'Daily price moved ' + (chg >= 0 ? '+' : '') + chg.toFixed(2) + '% (threshold: ±' + priceThresh + '%)',
          severity: Math.abs(chg) >= (priceThresh * 1.5) ? 'CRITICAL' : 'WARNING'
        });
      }

      var vol = c.volume || 0;
      var avgVol = c.avg_volume_20d || 1;
      var ratio = parseFloat((vol / avgVol).toFixed(1));
      if (ratio >= volThresh) {
        volumeSpikes.push({
          ticker: c.ticker,
          symbol: c.symbol,
          name: c.name,
          volume: vol,
          avg_volume_20d: avgVol,
          volume_ratio: ratio,
          message: 'Trading volume is ' + ratio + 'x higher than 20-day average (' + vol.toLocaleString() + ' vs avg ' + avgVol.toLocaleString() + ')',
          severity: ratio >= (volThresh * 1.5) ? 'CRITICAL' : 'WARNING'
        });
      }
    });

    var materialCats = ['results', 'M&A', 'management_change', 'capex', 'litigation', 'pledging'];
    this.data.announcements.forEach(function(item) {
      if (materialCats.indexOf(item.category) !== -1 || item.priority === 'HIGH') {
        materialFilings.push(item);
      }
    });

    return {
      summary: {
        total_triggered: priceAnomalies.length + volumeSpikes.length + materialFilings.length,
        price_anomalies_count: priceAnomalies.length,
        volume_spikes_count: volumeSpikes.length,
        material_filings_count: materialFilings.length,
        active_thresholds: {
          price_threshold_pct: priceThresh,
          volume_multiplier: volThresh,
          lookback_hours: 24
        }
      },
      price_anomalies: priceAnomalies,
      volume_spikes: volumeSpikes,
      material_filings: materialFilings
    };
  },

